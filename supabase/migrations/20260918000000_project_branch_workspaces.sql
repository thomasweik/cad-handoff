create policy "CAD projects are readable by team members"
on public.cad_projects
for select
to authenticated
using (true);

create policy "Team members can create CAD projects"
on public.cad_projects
for insert
to authenticated
with check ((select auth.uid()) = created_by);

create policy "CAD branches are readable by team members"
on public.cad_branches
for select
to authenticated
using (true);

create policy "Team members can create their own CAD branches"
on public.cad_branches
for insert
to authenticated
with check ((select auth.uid()) = owner_id);


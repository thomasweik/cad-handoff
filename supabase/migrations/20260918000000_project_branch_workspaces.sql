on public.cad_branches
for update
to authenticated
using ((select auth.uid()) = owner_id)
with check ((select auth.uid()) = owner_id);

create or replace function public.merge_cad_branch(p_branch_id bigint)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  branch_project_id bigint;
  latest_package_id public.cad_packages.id%type;
begin
  select project_id
  into branch_project_id
  from public.cad_branches
  where id = p_branch_id
    and owner_id = (select auth.uid())
    and merged_at is null;

  if branch_project_id is null then
    raise exception 'Only the owner can merge an active branch.';
  end if;

  select id
  into latest_package_id
  from public.cad_packages
  where branch_id = p_branch_id
  order by version_number desc, created_at desc
  limit 1;

  if latest_package_id is null then
    raise exception 'Upload a package version before merging this branch.';
  end if;

  update public.cad_packages
  set is_primary = false
  where project_id = branch_project_id
    and is_primary = true;

  update public.cad_packages
  set
    is_primary = true,
    promoted_at = now()
  where id = latest_package_id;

  update public.cad_branches
  set merged_at = now()
  where id = p_branch_id;
end;
$$;

revoke all on function public.merge_cad_branch(bigint) from public, anon;
grant execute on function public.merge_cad_branch(bigint) to authenticated;
